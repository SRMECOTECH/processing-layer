-- Nothing the platform receives is ever thrown away. Kafka keeps every topic for a month; these two tables keep the
-- records that did NOT become positions for good, so they outlive Kafka's retention.

-- Dead letters: records a consumer (listener or Kafka Streams) could not handle and parked in gps.dead-letters.
-- Rows are never deleted: a replay or a discard only changes the status, so the history of every record stays.
CREATE TABLE dead_letter (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source                 varchar(20)  NOT NULL,
    original_topic         varchar(250),
    original_partition     integer,
    original_offset        bigint,
    consumer_group         varchar(250),
    record_key             varchar(250),
    record_value           text,
    exception_class        varchar(500),
    exception_message      text,
    stacktrace             text,
    parked_at              timestamptz  NOT NULL,
    dead_letter_partition  integer      NOT NULL,
    dead_letter_offset     bigint       NOT NULL,
    status                 varchar(10)  NOT NULL DEFAULT 'PARKED',
    replay_count           integer      NOT NULL DEFAULT 0,
    last_replayed_at       timestamptz,
    resolution_note        text,
    archived_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT dead_letter_status_values CHECK (status IN ('PARKED', 'REPLAYED', 'DISCARDED')),
    -- the same dead letter delivered twice is archived once (offset + time: unique even if the topic is ever recreated)
    CONSTRAINT dead_letter_archived_once UNIQUE (dead_letter_partition, dead_letter_offset, parked_at)
);

CREATE INDEX dead_letter_status_time ON dead_letter (status, parked_at DESC);
CREATE INDEX dead_letter_topic_time  ON dead_letter (original_topic, parked_at DESC);
CREATE INDEX dead_letter_key         ON dead_letter (record_key);

-- Rejected frames: frames the normalizer refused (bad coordinates, duplicates, stale ...), with the reason and the
-- payload exactly as it arrived. Until now they only reached the service log.
CREATE TABLE rejected_frame (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imei              varchar(50),
    rejection_reason  text         NOT NULL,
    original_payload  text         NOT NULL,
    rejected_at       timestamptz  NOT NULL,
    payload_hash      char(32)     NOT NULL,
    archived_at       timestamptz  NOT NULL DEFAULT now(),
    -- a redelivered rejection (same payload, same moment) is stored once
    CONSTRAINT rejected_frame_archived_once UNIQUE (rejected_at, payload_hash)
);

CREATE INDEX rejected_frame_time      ON rejected_frame (rejected_at DESC);
CREATE INDEX rejected_frame_imei_time ON rejected_frame (imei, rejected_at DESC);
