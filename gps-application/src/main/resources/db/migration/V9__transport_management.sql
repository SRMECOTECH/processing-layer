-- The transport management layer (TMS) on top of the GPS platform. Three kinds of company use it:
--   GPS provider (us)  : fits the devices, maps device <-> vehicle, sees everything (role DEVELOPER)
--   transporter        : owns or hires the trucks, uploads the shipments it carries (role TRANSPORTER)
--   consigner          : sends the goods (steel ...) and follows its shipments to the consignee (role CONSIGNER)
-- The consignee (who receives the goods) is a name on the shipment, not a login.

-- 1. What kind of company a tenant is. The tenants seeded from the GPS pings are truck owners: transporters.
--    external_code: the company's number in the consigner's TMS (the transporter's vendor code, the consignor id).
ALTER TABLE tenant
    ADD COLUMN kind          varchar(20) NOT NULL DEFAULT 'TRANSPORTER',
    ADD COLUMN external_code varchar(60),
    ADD CONSTRAINT tenant_kind_values CHECK (kind IN ('GPS_PROVIDER', 'TRANSPORTER', 'CONSIGNER'));

CREATE UNIQUE INDEX tenant_kind_external_code ON tenant (kind, external_code) WHERE external_code IS NOT NULL;

-- 2. Who may sign in, and as what. The sign-in page asks for the role as well as user id and password, so a user id
--    is unique per role. A transporter or consigner user belongs to exactly one company and only sees its data.
--    password_hash: PBKDF2-HMAC-SHA256 (PasswordHashing), never the password.
CREATE TABLE app_user (
    id             uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    role           varchar(20)  NOT NULL,
    username       varchar(80)  NOT NULL,
    display_name   varchar(120) NOT NULL,
    tenant_id      uuid         REFERENCES tenant (id),
    password_hash  varchar(200) NOT NULL,
    active         boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    last_login_at  timestamptz,
    CONSTRAINT app_user_role_values CHECK (role IN ('DEVELOPER', 'TRANSPORTER', 'CONSIGNER')),
    CONSTRAINT app_user_company_for_business_roles CHECK (role = 'DEVELOPER' OR tenant_id IS NOT NULL)
);

CREATE UNIQUE INDEX app_user_role_username ON app_user (role, lower(username));

-- The key that signs sign-in tokens (PortalTokens). Made once, here, so it survives restarts and never sits in a
-- config file; replacing it signs everyone out.
CREATE TABLE auth_key (
    id          smallint     PRIMARY KEY,
    secret      varchar(128) NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT auth_key_single_row CHECK (id = 1)
);

