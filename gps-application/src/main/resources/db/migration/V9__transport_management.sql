-- 4. Every shipment file uploaded (Excel, CSV, pasted rows, or the smart_truck trips), with what it did. Uploading the
--    same file again is harmless: its rows are found unchanged (row_hash) and nothing is written twice.
CREATE TABLE shipment_import (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name       varchar(255) NOT NULL,
    file_sha256     varchar(64)  NOT NULL,
    format          varchar(12)  NOT NULL,
    uploaded_by     varchar(80)  NOT NULL,
    uploaded_role   varchar(20)  NOT NULL,
    tenant_id       uuid         REFERENCES tenant (id),
    rows_total      integer      NOT NULL,
    rows_created    integer      NOT NULL,
    rows_updated    integer      NOT NULL,
    rows_unchanged  integer      NOT NULL,
    rows_failed     integer      NOT NULL,
    problems        jsonb        NOT NULL DEFAULT '[]'::jsonb,
    column_mapping  jsonb        NOT NULL DEFAULT '{}'::jsonb,
    uploaded_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX shipment_import_file ON shipment_import (file_sha256);
CREATE INDEX shipment_import_recent ON shipment_import (uploaded_at DESC);

-- 5. A shipment: one trip of one truck carrying one consigner's goods, as the transporter's file describes it
--    (the smart_truck tta_trips layout), plus what the GPS says about it.
--
--    Identity: the trip number within the transporter. A row uploaded again (the same file twice, a corrected file,
--    the consigner's next export) updates its shipment instead of adding one - "MULTIPLE UPLOAD" can't duplicate.
--
--    The GPS columns are written by the shipment-tracking module, always as the EARLIEST reading that proves them
--    (departure = first reading outside the origin fence after the gate-out, arrival = first reading inside the
--    destination fence after being outside it). A reading delivered twice, late (device memory) or replayed can
--    therefore only confirm or move a moment earlier, never invent a second one.
CREATE TABLE shipment (
    id                       bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_no                  varchar(60)      NOT NULL,
    source                   varchar(12)      NOT NULL,
    transporter_tenant_id    uuid             NOT NULL REFERENCES tenant (id),
    transporter_code         varchar(60),
    consigner_tenant_id      uuid             REFERENCES tenant (id),
    consigner_code           varchar(60),
    consigner_unit           varchar(255),
    consignee_name           varchar(255),
    consignee_address        varchar(500),
    vehicle_registration_no  varchar(50)      NOT NULL,
    device_imei              varchar(50),
    vehicle_type             varchar(100),
    trip_class               varchar(20),
    trip_type                varchar(100),
    origin_name              varchar(255),
    destination_name         varchar(255),
    load_plant               varchar(255),
    origin_place_id          bigint           REFERENCES place (id),
    destination_place_id     bigint           REFERENCES place (id),
    booked_at                timestamptz,
    dispatched_at            timestamptz      NOT NULL,
    eta_at                   timestamptz,
    reported_ata_at          timestamptz,
    reported_end_at          timestamptz,
    invoice_no               varchar(100),
    shipment_ref             varchar(100),
    gate_entry_no            varchar(100),
    card_id                  varchar(50),
    route_id                 varchar(30),
    material                 varchar(500),
    quantity                 numeric(14, 2),
    driver_name              varchar(255),
    driver_mobile            varchar(20),
    source_status            varchar(30),
    close_reason             varchar(255),
    left_origin_at           timestamptz,
    outside_destination_at   timestamptz,
    arrived_at               timestamptz,
    last_reading_at          timestamptz,
    last_latitude            double precision,
    last_longitude           double precision,
    last_speed_kmph          integer,
    closed_at                timestamptz,
    closed_reason            varchar(60),
    row_hash                 varchar(64)      NOT NULL,
    import_id                bigint           REFERENCES shipment_import (id),
    created_at               timestamptz      NOT NULL DEFAULT now(),
    updated_at               timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT shipment_trip_once_per_transporter UNIQUE (transporter_tenant_id, trip_no)
);

-- the tracking module looks up a reading's shipments by vehicle (or by the IMEI in the file) and time
CREATE INDEX shipment_vehicle_dispatch ON shipment (vehicle_registration_no, dispatched_at DESC);
CREATE INDEX shipment_device_dispatch ON shipment (device_imei, dispatched_at DESC);
CREATE INDEX shipment_consigner ON shipment (consigner_tenant_id, dispatched_at DESC);
CREATE INDEX shipment_transporter ON shipment (transporter_tenant_id, dispatched_at DESC);

-- portal alert lists join events to the shipment windows by vehicle
CREATE INDEX vehicle_event_vehicle_time ON vehicle_event (vehicle_registration_no, started_at DESC);
