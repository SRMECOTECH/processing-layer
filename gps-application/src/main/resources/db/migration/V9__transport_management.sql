-- 3. Places: the geofences a shipment starts in and ends in. code is the normalised name the shipment files use
--    (s_org_node_name / s_dest_node_name: "ADITYAPUR"), so an uploaded row finds its fence by name.
CREATE TABLE place (
    id          bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(255)     NOT NULL,
    name        varchar(255)     NOT NULL,
    role        varchar(12)      NOT NULL,
    latitude    double precision NOT NULL,
    longitude   double precision NOT NULL,
    radius_m    integer          NOT NULL,
    source      varchar(20)      NOT NULL DEFAULT 'MANUAL',
    active      boolean          NOT NULL DEFAULT true,
    created_at  timestamptz      NOT NULL DEFAULT now(),
    updated_at  timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT place_once_per_role UNIQUE (code, role),
    CONSTRAINT place_role_values CHECK (role IN ('ORIGIN', 'DESTINATION')),
    CONSTRAINT place_position_valid CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180),
    CONSTRAINT place_radius_sensible CHECK (radius_m BETWEEN 50 AND 50000)
);

