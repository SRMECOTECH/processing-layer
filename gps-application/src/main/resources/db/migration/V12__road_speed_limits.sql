-- Road speed limits (module speed-violation, docs/ROAD_SPEED_GUIDE.md).
--
-- road_segment is the library of road pieces trucks have driven, map-matched by Valhalla (trace_attributes on the
-- all-India OpenStreetMap of the HP home server): learned from smart_truck trips on request and from the live readings
-- every few minutes. The live speed check finds the road under each reading here, in memory, without asking Valhalla.
-- Not emptied by "Clear database": it is knowledge of the roads, not telemetry.

CREATE TABLE road_segment (
    id                 bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- way id + both ends rounded to ~1 m: the same piece matched again is the same row
    segment_key        varchar(120)     NOT NULL UNIQUE,
    way_id             bigint           NOT NULL,
    road_name          varchar(255),
    road_ref           varchar(40),
    -- Valhalla: motorway, trunk, primary, secondary, tertiary, unclassified, residential, service_other
    road_class         varchar(20)      NOT NULL,
    -- Valhalla's road density 0..15: from road_speed setting town-density-from on it counts as a town road
    density            integer          NOT NULL DEFAULT 0,
    lane_count         integer          NOT NULL DEFAULT 0,
    state_code         varchar(10),
    -- OpenStreetMap maxspeed (rare in India; tagged for cars, so it counts only when lower than the table's);
    -- a limit set by hand beats both
    osm_limit_kmph     integer,
    manual_limit_kmph  integer,
    manual_note        varchar(255),
    length_m           double precision NOT NULL,
    -- the line, encoded polyline (precision 6)
    shape              text             NOT NULL,
    min_lat            double precision NOT NULL,
    max_lat            double precision NOT NULL,
    min_lon            double precision NOT NULL,
    max_lon            double precision NOT NULL,
    times_matched      integer          NOT NULL DEFAULT 1,
    first_seen_at      timestamptz      NOT NULL DEFAULT now(),
    updated_at         timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT road_segment_manual_limit_range CHECK (manual_limit_kmph IS NULL OR manual_limit_kmph BETWEEN 5 AND 150)
);

CREATE INDEX road_segment_ref  ON road_segment (road_ref);
CREATE INDEX road_segment_name ON road_segment (road_name);

-- The limit by road class and area for goods vehicles, '*' = every state; a state's own row beats it. Starting values:
-- the national limits for goods vehicles (80 on expressways and divided 4-lane roads, 60 elsewhere), lower in towns
-- and on minor roads. Check them per state (Road speed limits page).
CREATE TABLE road_speed_limit (
    road_class             varchar(20)  NOT NULL,
    area                   varchar(5)   NOT NULL,
    state_code             varchar(10)  NOT NULL DEFAULT '*',
    limit_kmph             integer      NOT NULL,
    -- on a divided road with 2+ lanes in the direction of travel; null = limit_kmph
    multi_lane_limit_kmph  integer,
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (road_class, area, state_code),
    CONSTRAINT road_speed_limit_area_values CHECK (area IN ('TOWN', 'OPEN')),
    CONSTRAINT road_speed_limit_range CHECK (limit_kmph BETWEEN 5 AND 150
        AND (multi_lane_limit_kmph IS NULL OR multi_lane_limit_kmph BETWEEN 5 AND 150))
);

