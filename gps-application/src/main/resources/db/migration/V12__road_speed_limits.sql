-- How far each device's live readings have been map-matched. Emptied with the telemetry by "Clear database".
CREATE TABLE road_match_cursor (
    imei           varchar(50)  PRIMARY KEY,
    matched_until  timestamptz  NOT NULL,
    updated_at     timestamptz  NOT NULL DEFAULT now()
);

-- The day-end road report: one row per vehicle per day per road (road + class + limit), rebuilt from gps_position for
-- today and yesterday every few minutes. A day is only rewritten while it still has positions, so the rows of days
-- whose telemetry was cleared stay.
CREATE TABLE vehicle_day_road (
    day                      date              NOT NULL,
    imei                     varchar(50)       NOT NULL,
    road_key                 varchar(400)      NOT NULL,
    tenant_code              varchar(40),
    vehicle_registration_no  varchar(50),
    road_label               varchar(300)      NOT NULL,
    road_ref                 varchar(40),
    road_class               varchar(20)       NOT NULL,
    area                     varchar(5)        NOT NULL,
    state_code               varchar(10),
    limit_kmph               integer           NOT NULL,
    -- MANUAL, OSM, TABLE, or COMPANY (no known road there, or the road allows more than the vehicle's own limit)
    limit_source             varchar(10)       NOT NULL,
    readings                 integer           NOT NULL,
    distance_m               double precision  NOT NULL,
    moving_s                 bigint            NOT NULL,
    max_speed_kmph           integer           NOT NULL,
    avg_moving_speed_kmph    double precision  NOT NULL,
    -- readings faster than the limit, without the over-speed rule's minimum duration (exposure)
    over_readings            integer           NOT NULL,
    over_distance_m          double precision  NOT NULL,
    over_s                   bigint            NOT NULL,
    max_excess_kmph          integer           NOT NULL,
    computed_at              timestamptz       NOT NULL DEFAULT now(),
    PRIMARY KEY (day, imei, road_key)
);

CREATE INDEX vehicle_day_road_vehicle ON vehicle_day_road (imei, day);
