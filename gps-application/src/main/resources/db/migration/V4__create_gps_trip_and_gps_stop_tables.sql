-- Trips and stops detected by consumer group gps-trip-service (Traccar computes these on request;
-- here they are written as the readings arrive). Tenant and vehicle are readable codes, as in gps_position,
-- taken from the device_assignment valid at the time of the readings.
--
-- A trip or stop is identified by (imei, start_recorded_at): a replayed reading produces the same key,
-- and the row is updated instead of stored twice.

CREATE TABLE gps_trip (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imei                      varchar(50)      NOT NULL,
    tenant_code               varchar(40),
    vehicle_registration_no   varchar(50),
    start_recorded_at         timestamptz      NOT NULL,
    end_recorded_at           timestamptz      NOT NULL,
    start_latitude            double precision NOT NULL,
    start_longitude           double precision NOT NULL,
    end_latitude              double precision NOT NULL,
    end_longitude             double precision NOT NULL,
    -- sum of distance_from_previous of the in-order readings, never "end odometer - start odometer"
    distance_m                double precision NOT NULL,
    duration_s                bigint           NOT NULL,
    max_speed_kmph            integer          NOT NULL,
    avg_speed_kmph            double precision NOT NULL,
    reading_count             integer          NOT NULL,
    -- readings that arrived late for this trip; they are not in distance/duration (see gps_trip_late_reading)
    late_reading_count        integer          NOT NULL DEFAULT 0,
    -- OPEN: the vehicle is still driving, the end moves with every reading. CLOSED: final.
    status                    varchar(10)      NOT NULL,
    updated_at                timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT gps_trip_status_values CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT gps_trip_ends_after_it_starts CHECK (end_recorded_at >= start_recorded_at),
    -- Traccar's trips report once said -1020 m because of one late reading; this table refuses that.
    CONSTRAINT gps_trip_distance_not_negative CHECK (distance_m >= 0),
    CONSTRAINT gps_trip_one_trip_per_device_per_start UNIQUE (imei, start_recorded_at)
);

CREATE INDEX gps_trip_vehicle_time ON gps_trip (vehicle_registration_no, start_recorded_at DESC);

CREATE TABLE gps_stop (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imei                      varchar(50)      NOT NULL,
    tenant_code               varchar(40),
    vehicle_registration_no   varchar(50),
    start_recorded_at         timestamptz      NOT NULL,
    end_recorded_at           timestamptz      NOT NULL,
    latitude                  double precision NOT NULL,
    longitude                 double precision NOT NULL,
    duration_s                bigint           NOT NULL,
    reading_count             integer          NOT NULL,
    status                    varchar(10)      NOT NULL,
    updated_at                timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT gps_stop_status_values CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT gps_stop_ends_after_it_starts CHECK (end_recorded_at >= start_recorded_at),
    CONSTRAINT gps_stop_one_stop_per_device_per_start UNIQUE (imei, start_recorded_at)
);

CREATE INDEX gps_stop_vehicle_time ON gps_stop (vehicle_registration_no, start_recorded_at DESC);

-- Every late reading the trip detection skipped, once (a Kafka redelivery is not counted again).
-- trip_start_recorded_at points to the trip it fell into (null: it fell into a stop or no trip).
-- This is also the work list for a later "repair" job that recomputes those trips from gps_position.
CREATE TABLE gps_trip_late_reading (
    imei                      varchar(50)  NOT NULL,
    recorded_at               timestamptz  NOT NULL,
    trip_start_recorded_at    timestamptz,
    noted_at                  timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (imei, recorded_at)
);
