-- GPS positions after Flink processing, with the tenant and vehicle resolved from master data.
-- Tenant and vehicle are stored as readable codes (not foreign keys): telemetry is written fast,
-- read in reports, and will later move to a time-series store.

CREATE TABLE gps_position (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imei                      varchar(50)      NOT NULL,
    tenant_code               varchar(40),
    vehicle_registration_no   varchar(50),
    recorded_at               timestamptz      NOT NULL,
    latitude                  double precision NOT NULL,
    longitude                 double precision NOT NULL,
    speed_kmph                integer          NOT NULL,
    movement_status           varchar(10)      NOT NULL,
    distance_from_previous_m  double precision NOT NULL,
    seconds_since_previous    bigint           NOT NULL,
    arrived_out_of_order      boolean          NOT NULL,
    processed_at              timestamptz      NOT NULL,
    stored_at                 timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT gps_position_latitude_range  CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT gps_position_longitude_range CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT gps_position_movement_status_values CHECK (movement_status IN ('MOVING', 'STOPPED')),
    -- Kafka delivers at-least-once, so the same reading can arrive twice; it is stored once.
    CONSTRAINT gps_position_one_reading_per_device_per_moment UNIQUE (imei, recorded_at)
);

CREATE INDEX gps_position_vehicle_time ON gps_position (vehicle_registration_no, recorded_at DESC);
CREATE INDEX gps_position_stored_at    ON gps_position (stored_at DESC);
