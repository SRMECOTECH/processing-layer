-- Route deviation, live ETA and waypoints (modules route-deviation and waypoints, docs/ROUTE_DEVIATION_ETA_DESIGN.md).
--
-- A route plan is one trip of one truck along a road route planned by Valhalla (the HP home server) or GraphHopper
-- (this laptop): made automatically for every open shipment with an origin and a destination geofence, or by hand
-- (Alerts -> Route deviation -> Plan a route). The modules project every reading onto the plan's line; Redis holds the
-- per-reading state, this table the plan itself and the live numbers whenever they change.

CREATE TABLE route_plan (
    id                       bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id              bigint           REFERENCES shipment (id) ON DELETE CASCADE,
    imei                     varchar(50),
    vehicle_registration_no  varchar(50)      NOT NULL,
    tenant_code              varchar(80),
    source                   varchar(12)      NOT NULL,
    -- ACTIVE while the truck is on its way; ARRIVED at the destination; CANCELLED by hand; CLOSED when its shipment
    -- closed without an arrival, or a newer plan for the same truck replaced it
    status                   varchar(12)      NOT NULL DEFAULT 'ACTIVE',
    origin_name              varchar(255),
    origin_place_id          bigint           REFERENCES place (id),
    origin_lat               double precision NOT NULL,
    origin_lon               double precision NOT NULL,
    destination_name         varchar(255),
    destination_place_id     bigint           REFERENCES place (id),
    destination_lat          double precision NOT NULL,
    destination_lon          double precision NOT NULL,
    destination_radius_m     double precision NOT NULL,
    engine                   varchar(20)      NOT NULL,
    costing                  varchar(20)      NOT NULL,
    -- the current line: version 1 is the dispatch plan, each ROUTE_ALTERNATE adds one (a re-plan from where the truck was)
    version                  integer          NOT NULL DEFAULT 1,
    reason                   varchar(20)      NOT NULL,
    shape                    text             NOT NULL,
    timings                  jsonb            NOT NULL DEFAULT '[]'::jsonb,
    length_m                 double precision NOT NULL,
    planned_s                double precision NOT NULL,
    -- distance already done before the current version began
    offset_m                 double precision NOT NULL DEFAULT 0,
    first_shape              text             NOT NULL,
    first_length_m           double precision NOT NULL,
    first_planned_s          double precision NOT NULL,
    -- actual / planned driving time this truck starts with: the lane's median of earlier arrived trips, else 1
    initial_pace             double precision NOT NULL,
    planned_start_at         timestamptz      NOT NULL,
    -- live numbers, written by the route-deviation module when they change
    route_status             varchar(12)      NOT NULL DEFAULT 'WAITING',
    departed_at              timestamptz,
    promised_eta_at          timestamptz,
    eta_at                   timestamptz,
    arrived_at               timestamptz,
    pace                     double precision,
    chainage_m               double precision,
    cross_track_m            double precision,
    last_reading_at          timestamptz,
    last_lat                 double precision,
    last_lon                 double precision,
    deviations               integer          NOT NULL DEFAULT 0,
    deviation_km             double precision NOT NULL DEFAULT 0,
    deviation_minutes        integer          NOT NULL DEFAULT 0,
    wrong_ways               integer          NOT NULL DEFAULT 0,
    alternates               integer          NOT NULL DEFAULT 0,
    created_by               varchar(80),
    created_at               timestamptz      NOT NULL DEFAULT now(),
    updated_at               timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT route_plan_status_values CHECK (status IN ('ACTIVE', 'ARRIVED', 'CANCELLED', 'CLOSED')),
    CONSTRAINT route_plan_source_values CHECK (source IN ('SHIPMENT', 'MANUAL')),
    CONSTRAINT route_plan_route_status_values CHECK (route_status IN ('WAITING', 'ON_ROUTE', 'SUSPECT', 'OFF_ROUTE', 'ARRIVED')),
    CONSTRAINT route_plan_positive CHECK (length_m > 0 AND planned_s > 0 AND destination_radius_m > 0)
);

-- a shipment is planned once; the modules find a truck's plan by vehicle or device
CREATE UNIQUE INDEX route_plan_one_per_shipment ON route_plan (shipment_id) WHERE shipment_id IS NOT NULL;
CREATE INDEX route_plan_active_vehicle ON route_plan (vehicle_registration_no) WHERE status = 'ACTIVE';
CREATE INDEX route_plan_active_imei ON route_plan (imei) WHERE status = 'ACTIVE';
CREATE INDEX route_plan_recent ON route_plan (planned_start_at DESC);
-- the lane's pace history (median of arrived trips between the same two geofences)
CREATE INDEX route_plan_lane ON route_plan (origin_place_id, destination_place_id) WHERE status = 'ARRIVED';

-- The stops on the way: waypoints planned by hand (MANUAL) and the geofences the planned line crosses (FENCE).
CREATE TABLE route_stop (
    id             bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id        bigint           NOT NULL REFERENCES route_plan (id) ON DELETE CASCADE,
    seq            integer          NOT NULL,
    kind           varchar(10)      NOT NULL,
    place_id       bigint           REFERENCES place (id),
    name           varchar(255)     NOT NULL,
    latitude       double precision NOT NULL,
    longitude      double precision NOT NULL,
    radius_m       double precision NOT NULL,
    -- distance along the current line; -1 when the current line does not pass it
    chainage_m     double precision NOT NULL,
    stay_min       integer          NOT NULL DEFAULT 0,
    status         varchar(10)      NOT NULL DEFAULT 'PENDING',
    arrived_at     timestamptz,
    departed_at    timestamptz,
    missed_at      timestamptz,
    minutes_inside integer,
    out_of_order   boolean          NOT NULL DEFAULT false,
    updated_at     timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT route_stop_once UNIQUE (plan_id, seq),
    CONSTRAINT route_stop_kind_values CHECK (kind IN ('MANUAL', 'FENCE')),
    CONSTRAINT route_stop_status_values CHECK (status IN ('PENDING', 'INSIDE', 'ARRIVED', 'DEPARTED', 'PASSED', 'MISSED'))
);

CREATE INDEX route_stop_plan ON route_stop (plan_id, seq);
