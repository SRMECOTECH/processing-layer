-- Road Intelligence, more data for later analysis (docs/ROAD_INTELLIGENCE.md, "Data we keep"):
--   5. points on the road: junctions, toll booths, gates, borders (road_point)
--   6. the road of every vehicle event (vehicle_event.road_segment_id, road_label)
--   7. the history of every speed-limit change (road_limit_change)
--   8. one row per Valhalla map-matching run (road_match_run)

-- 5. The end node of every matched road edge, as Valhalla's map matching describes it (node.* attributes of
--    trace_attributes): its type (street_intersection, toll_booth, gate, border_control, ...), traffic signal, fork, and
--    the other roads meeting there. Knowledge of the roads like road_segment: kept by "Clear database".
CREATE TABLE road_point (
    id                 bigint            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- the position rounded to about a metre: the same node matched again is the same row
    point_key          varchar(40)       NOT NULL UNIQUE,
    latitude           double precision  NOT NULL,
    longitude          double precision  NOT NULL,
    node_type          varchar(30)       NOT NULL,
    traffic_signal     boolean           NOT NULL DEFAULT false,
    fork               boolean           NOT NULL DEFAULT false,
    -- roads meeting here besides the one driven: how many, their classes ("trunk,service_other"), the raw list
    side_roads         integer           NOT NULL DEFAULT 0,
    side_road_classes  varchar(200),
    intersecting       jsonb,
    -- the road piece driven into this point (road_segment.segment_key; not a foreign key, see V13)
    segment_key        varchar(120),
    times_seen         integer           NOT NULL DEFAULT 1,
    first_seen_at      timestamptz       NOT NULL DEFAULT now(),
    updated_at         timestamptz       NOT NULL DEFAULT now()
);

CREATE INDEX road_point_type ON road_point (node_type);

-- 6. The road a vehicle event happened on: the road saved on the vehicle's reading at (or just before) the event's start,
--    set after the live map matching has covered it. The modules that raise events are not touched.
ALTER TABLE vehicle_event
    ADD COLUMN road_segment_id  bigint,
    ADD COLUMN road_label       varchar(300),
    ADD COLUMN road_class       varchar(20);

CREATE INDEX vehicle_event_road ON vehicle_event (road_label, event_type);

-- 7. Every change of a speed limit: one road piece, a whole road, or a row of the limit table. changed_by is the console
--    user the dashboard reported (header X-Dashboard-User), or "api" for direct calls.
CREATE TABLE road_limit_change (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at      timestamptz   NOT NULL DEFAULT now(),
    changed_by      varchar(100)  NOT NULL,
    -- PIECE, ROAD, TABLE_ROW, TABLE_ROW_DELETED
    scope           varchar(20)   NOT NULL,
    -- what was changed: "piece 812", "NH19 Grand Trunk Road", "trunk/OPEN/*"
    target          varchar(300)  NOT NULL,
    pieces          integer,
    old_limit_kmph  integer,
    new_limit_kmph  integer,
    old_multi_lane_limit_kmph  integer,
    new_multi_lane_limit_kmph  integer,
    note            varchar(255)
);

CREATE INDEX road_limit_change_time ON road_limit_change (changed_at DESC);

-- 8. One row per map-matching run: a smart_truck trip learned on request, or one device's live readings. Data quality
--    over time, and when Valhalla was down or slow. Kept by "Clear database".
CREATE TABLE road_match_run (
    id                bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at        timestamptz   NOT NULL,
    finished_at       timestamptz   NOT NULL,
    -- LIVE (a device's new readings) or TRIP (a smart_truck trip on request)
    kind              varchar(10)   NOT NULL,
    imei              varchar(50),
    trip_number       bigint,
    readings_from     timestamptz,
    readings_until    timestamptz,
    points_sent       integer       NOT NULL DEFAULT 0,
    matched_points    integer       NOT NULL DEFAULT 0,
    unmatched_points  integer       NOT NULL DEFAULT 0,
    calls             integer       NOT NULL DEFAULT 0,
    failed_pieces     integer       NOT NULL DEFAULT 0,
    pieces_matched    integer       NOT NULL DEFAULT 0,
    pieces_added      integer       NOT NULL DEFAULT 0,
    points_found      integer       NOT NULL DEFAULT 0,
    valhalla_ms       bigint        NOT NULL DEFAULT 0,
    -- OK, PARTLY (some pieces not matchable), DOWN (Valhalla did not answer), FAILED
    outcome           varchar(10)   NOT NULL,
    message           varchar(500),
    valhalla_url      varchar(200),
    valhalla_version  varchar(40),
    tiles_built_at    timestamptz
);

CREATE INDEX road_match_run_time ON road_match_run (started_at DESC);
