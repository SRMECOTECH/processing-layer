-- Events raised by the stream consumers (over-speed, stoppage, parking, idling, ignition, harsh driving ...).
-- An episode is written when it starts (OPEN) and again when it ends (CLOSED) with the same event_key,
-- so the row is upserted - which also makes a Kafka redelivery harmless.
CREATE TABLE vehicle_event (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key                varchar(120) NOT NULL UNIQUE,
    imei                     varchar(50)  NOT NULL,
    tenant_code              varchar(40),
    vehicle_registration_no  varchar(50),
    event_type               varchar(40)  NOT NULL,
    severity                 varchar(10)  NOT NULL,
    status                   varchar(10)  NOT NULL,
    started_at               timestamptz  NOT NULL,
    ended_at                 timestamptz,
    latitude                 double precision NOT NULL,
    longitude                double precision NOT NULL,
    detected_by              varchar(40)  NOT NULL,
    details                  jsonb        NOT NULL DEFAULT '{}'::jsonb,
    created_at               timestamptz  NOT NULL DEFAULT now(),
    updated_at               timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT vehicle_event_status_values CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE INDEX vehicle_event_type_time   ON vehicle_event (event_type, started_at DESC);
CREATE INDEX vehicle_event_imei_time   ON vehicle_event (imei, started_at DESC);
CREATE INDEX vehicle_event_recent      ON vehicle_event (updated_at DESC);
