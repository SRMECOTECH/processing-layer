-- Road Intelligence data for later analysis (docs/ROAD_INTELLIGENCE.md, "Data we keep"):
--   1. more of what Valhalla's map matching says about each road piece (road_segment)
--   2. the road each stored reading was on (gps_position), filled by the live map matching
--   3. road passes: each time a vehicle drove a road, entered to left (trip_road_pass)

-- 1. Road piece details. Checked on the HP's Valhalla (2026-11-15): use, one-way, bridge, tunnel, roundabout, toll,
--    curvature, its own expected speed, truck route and headings come back; surface is always paved_smooth (untagged),
--    elevation is empty (tiles built without it) and state/country are not returned. attributes keeps the whole edge
--    as Valhalla sent it, so a field needed later does not mean matching every road again.
ALTER TABLE road_segment
    ADD COLUMN road_use             varchar(30),
    -- forward / backward = one-way in the direction it was driven, both = two-way
    ADD COLUMN traversability       varchar(10),
    ADD COLUMN bridge               boolean,
    ADD COLUMN tunnel               boolean,
    ADD COLUMN roundabout           boolean,
    ADD COLUMN toll                 boolean,
    -- Valhalla's curvature 0..15 (0 straight)
    ADD COLUMN curvature            integer,
    -- the speed Valhalla expects a car to drive there (its routing speed), and how it got it (classified, tagged ...)
    ADD COLUMN valhalla_speed_kmph  integer,
    ADD COLUMN speed_type           varchar(20),
    ADD COLUMN truck_route          boolean,
    ADD COLUMN surface              varchar(30),
    ADD COLUMN begin_heading        integer,
    ADD COLUMN end_heading          integer,
    ADD COLUMN country_code         varchar(5),
    ADD COLUMN attributes           jsonb;

-- 2. The road under each reading: the nearest learned piece within the match distance (35 m), set when the live map
--    matching has covered the reading. Not a foreign key: forgetting the learned roads must not touch the readings.
ALTER TABLE gps_position
    ADD COLUMN road_segment_id  bigint,
    ADD COLUMN road_off_m       real;

-- 3. Road passes, rebuilt from gps_position for the readings the live map matching has covered: consecutive readings
--    of one vehicle on one road (label + class + limit, the day report's road key); a single reading on another road
--    between two of the same road (a junction) stays in the pass. Telemetry: emptied by "Clear database".
CREATE TABLE trip_road_pass (
    id                       bigint            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imei                     varchar(50)       NOT NULL,
    tenant_code              varchar(40),
    vehicle_registration_no  varchar(50),
    -- the detected trip (gps_trip) the pass started in, when there is one
    trip_id                  bigint,
    road_key                 varchar(400)      NOT NULL,
    road_label               varchar(300)      NOT NULL,
    road_ref                 varchar(40),
    road_class               varchar(20)       NOT NULL,
    area                     varchar(5)        NOT NULL,
    -- the road's own limit, and the limit the readings were judged by (the lower of it and the vehicle's company limit)
    road_limit_kmph          integer,
    limit_kmph               integer           NOT NULL,
    limit_source             varchar(10)       NOT NULL,
    entered_at               timestamptz       NOT NULL,
    left_at                  timestamptz       NOT NULL,
    readings                 integer           NOT NULL,
    pieces                   integer           NOT NULL,
    distance_m               double precision  NOT NULL,
    moving_s                 bigint            NOT NULL,
    stopped_s                bigint            NOT NULL,
    avg_moving_speed_kmph    double precision  NOT NULL,
    max_speed_kmph           integer           NOT NULL,
    -- what Valhalla expects on those pieces (length-weighted), to compare with how the truck really drove
    expected_speed_kmph      double precision,
    over_readings            integer           NOT NULL,
    over_s                   bigint            NOT NULL,
    max_excess_kmph          integer           NOT NULL,
    bridges                  integer           NOT NULL DEFAULT 0,
    max_curvature            integer,
    first_segment_id         bigint,
    last_segment_id          bigint,
    entry_lat                double precision  NOT NULL,
    entry_lon                double precision  NOT NULL,
    exit_lat                 double precision  NOT NULL,
    exit_lon                 double precision  NOT NULL,
    computed_at              timestamptz       NOT NULL DEFAULT now()
);

CREATE INDEX trip_road_pass_vehicle_time ON trip_road_pass (imei, entered_at);
CREATE INDEX trip_road_pass_road ON trip_road_pass (road_key, entered_at);
